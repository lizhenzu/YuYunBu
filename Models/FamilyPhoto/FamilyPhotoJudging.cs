//  주제 "우리 가족 추석맞이" · 100점 만점 = 심사 80 + 좋아요 20 (2026-09-29 A안 · 좋아요 20점)
//    함께함 20 · 추석 분위기 25 · 아이 표정 15 · 이야기·아이디어 10 · 완성도 10 · ❤️ 좋아요 20
//    좋아요 점수 = 20 × (이 사진 좋아요 ÷ 가장 많이 받은 사진 좋아요) — 화면을 열 때마다 새로 계산
