//  폰 화질 · 보정 · 합성은 점수에 넣지 않는다 (공정성 원칙).
//  PhotoId 로 사진과 잇는다 — 새 사진이 올라오면 여기에 줄을 더한다.
// ══════════════════════════════════════════════════════════════

public record FamilyPhotoJudgeScore(
    int    No,           // 심사 번호 (가족 참가 순 → 칸 순)
    int    PhotoId,
    int    Together,     // 가족의 함께함 /20
    int    Chuseok,      // 추석 분위기 /25
    int    Face,         // 아이의 표정·생동감 /15
    int    Story,        // 이야기·아이디어 /10
    int    Craft,        // 사진 완성도 /10
    string Praise,       // 칭찬 한 줄 (가족에게 그대로 보여 줘도 되는 말)
    string? StaffNote = null)   // 관리자 참고 (가족에게 보이지 않는다)
{
    /// <summary>심사 점수 (좋아요 빼고) /80</summary>
    public int JudgeTotal => Together + Chuseok + Face + Story + Craft;
}

