-- ────────────────────────────────────────────────────────────
--  3) 본문 맨 앞의 "**기도 제목: …**" 줄 제거 — PrayId 14, 22
-- ────────────────────────────────────────────────────────────
DECLARE @sep NVARCHAR(4) = CHAR(13) + CHAR(10) + CHAR(13) + CHAR(10);

UPDATE dbo.EntranceExamPray
   SET PrayText  = LTRIM(SUBSTRING(PrayText, CHARINDEX(@sep, PrayText) + LEN(@sep), LEN(PrayText))),
       UpdatedAt = DATEADD(HOUR, 16, GETDATE())
 WHERE PrayText LIKE N'**기도 제목:%'
   AND CHARINDEX(@sep, PrayText) > 0;

PRINT N'제목 줄 제거 — ' + CAST(@@ROWCOUNT AS NVARCHAR(10)) + N'건';


-- ────────────────────────────────────────────────────────────
--  4) 줄바꿈을 CRLF 로 통일 (화면이 \r\n 로 문단을 나눕니다)
-- ────────────────────────────────────────────────────────────
UPDATE dbo.EntranceExamPray
   SET PrayText = REPLACE(REPLACE(REPLACE(PrayText,
                    CHAR(13) + CHAR(10), CHAR(10)),
                    CHAR(13),            CHAR(10)),
                    CHAR(10),            CHAR(13) + CHAR(10))
 WHERE PrayId IN (27, 28, 29, 30, 31, 32, 33);

PRINT N'줄바꿈 정리 완료';


-- ────────────────────────────────────────────────────────────
--  결과 확인
-- ────────────────────────────────────────────────────────────
SELECT PrayId, SortOrder, Title, LEN(PrayText) AS len,
       (LEN(PrayText) - LEN(REPLACE(PrayText, CHAR(13)+CHAR(10)+CHAR(13)+CHAR(10), N''))) / 4 + 1 AS paragraphs,
       CASE WHEN PrayText LIKE N'%하여 주옵소서%' OR PrayText LIKE N'%하옵소서%' THEN N'예스러운체' ELSE N'해요체' END AS style
  FROM dbo.EntranceExamPray
 WHERE PrayId IN (27, 28, 29, 30, 31, 32, 33, 14, 22)
 ORDER BY SortOrder;

-- 남은 문제 확인 (모두 0 이어야 정상)
SELECT
    SUM(CASE WHEN PrayText LIKE N'%저를%' OR PrayText LIKE N'%저만%' OR PrayText LIKE N'%저의%'
              OR PrayText LIKE N'%저에게%' OR PrayText LIKE N'%제가%' OR PrayText LIKE N'%저는%'
             THEN 1 ELSE 0 END) AS first_person_left,
    SUM(CASE WHEN PrayText LIKE N'%기도 제목:%'  THEN 1 ELSE 0 END) AS label_left,
    SUM(CASE WHEN PrayText LIKE N'%해 주세요%'   THEN 1 ELSE 0 END) AS casual_left,
    SUM(CASE WHEN PrayText NOT LIKE N'%○○(이)%' THEN 1 ELSE 0 END) AS no_name_slot
  FROM dbo.EntranceExamPray;
GO
